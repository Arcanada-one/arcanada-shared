import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { parse } from "yaml";
import { format } from "prettier";
import { schemaDefinition, stateSchemas } from "../.manifest-stage/state.js";

// Build-time source custody only. Runtime resolution performs no file I/O.
const ids = [
  "retrieval.relevance",
  "retrieval.redundancy",
  "retrieval.coverage",
  "task.domain",
  "task.intent",
  "kc.role_relevance",
  "kc.skill_relevance",
  "health",
];
const entries = [];
for (const id of ids) {
  const yaml = await readFile(
    new URL(`../templates/${id}.yml`, import.meta.url),
    "utf8",
  );
  const template = parse(yaml);
  if (template.id !== id || template.version !== 1)
    throw new Error("Packaged template identity mismatch");
  const schema = template.state_schema_ref;
  entries.push({
    id,
    version: template.version,
    yaml,
    schema,
    schemaSha256:
      schema in stateSchemas
        ? createHash("sha256").update(schemaDefinition(schema)).digest("hex")
        : null,
    hold:
      id === "health"
        ? "HEALTH_STATE_CONTRACT_CONFLICT"
        : id === "task.domain"
          ? "DOMAIN_REGISTRY_MAPPING_NOT_QUALIFIED"
          : null,
  });
}
const source = `// Generated by scripts/compile-manifest.mjs; source bytes and schemas are bound.\nexport const manifest = ${JSON.stringify(entries, null, 2)} as const;\n`;
await writeFile(
  new URL("../src/manifest.ts", import.meta.url),
  await format(source, { parser: "typescript" }),
);
